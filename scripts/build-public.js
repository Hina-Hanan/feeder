const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const pub = path.join(root, "public");
const web = path.join(root, "web");
const assets = path.join(root, "assets");

function cpDir(src, dest) {
  if (!fs.existsSync(src)) return;
  fs.mkdirSync(dest, { recursive: true });
  for (const name of fs.readdirSync(src)) {
    const s = path.join(src, name);
    const d = path.join(dest, name);
    if (fs.statSync(s).isDirectory()) cpDir(s, d);
    else fs.copyFileSync(s, d);
  }
}

fs.rmSync(pub, { recursive: true, force: true });
fs.mkdirSync(pub, { recursive: true });
for (const f of fs.readdirSync(web)) {
  const s = path.join(web, f);
  if (fs.statSync(s).isFile()) fs.copyFileSync(s, path.join(pub, f));
}
cpDir(assets, path.join(pub, "assets"));

const wsUrl = process.env.FTF_WS_URL || "";
const sameOrigin = process.env.FTF_WS_SAME_ORIGIN === "1";
const wsConfig = `/** Generated by npm run build */\nwindow.FTF_WS_URL = ${JSON.stringify(wsUrl)};\nwindow.FTF_WS_SAME_ORIGIN = ${sameOrigin};\n`;
fs.writeFileSync(path.join(pub, "ws-config.js"), wsConfig);
fs.writeFileSync(path.join(web, "ws-config.js"), wsConfig);

console.log("Built public/ for Vercel");
if (wsUrl) console.log("WebSocket URL:", wsUrl);
